// OpticalEffect.java - Optical phenomenon shown by a specimen
package com.rockcollection.specimen;

/**
 * Optical phenomenon shown by a specimen
 */
public enum OpticalEffect {
    CHATOYANCY, // cat's-eye band, e.g. tiger's eye
    ASTERISM, // star, e.g. star sapphire
    IRIDESCENCE, // rainbow sheen, e.g. fire agate
    LABRADORESCENCE, // flash of colour, e.g. labradorite
    ADULARESCENCE, // floating glow, e.g. moonstone
    PLAY_OF_COLOR, // e.g. precious opal
    OPALESCENCE, // milky sheen
    AVENTURESCENCE, // glittering inclusions, e.g. sunstone
    COLOR_CHANGE // different colour under different light
}
