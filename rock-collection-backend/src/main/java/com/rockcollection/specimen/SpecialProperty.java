// SpecialProperty.java - Notable physical behaviour observed or tested on a specimen
package com.rockcollection.specimen;

/**
 * Notable physical behaviour observed or tested on a specimen
 */
public enum SpecialProperty {
    MAGNETIC, // attracted by a magnet
    FLUORESCENT, // glows under UV light
    PHOSPHORESCENT, // keeps glowing after UV is removed
    RADIOACTIVE, // registers on a Geiger counter
    EFFERVESCENT, // fizzes in dilute acid
    PIEZOELECTRIC, // produces charge under pressure
    PLEOCHROIC, // changes colour with viewing angle
    DOUBLE_REFRACTION, // shows a doubled image through it
    TRIBOLUMINESCENT, // emits light when struck or scratched
    SOLUBLE, // dissolves in water
    TASTE // has a distinctive taste, e.g. salty
}
