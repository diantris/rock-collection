// SpecimenForm.java - Physical form a specimen comes in
package com.rockcollection.specimen;

/**
 * Physical form a specimen comes in
 */
public enum SpecimenForm {
    ROUGH, // raw / natural piece
    CRYSTAL, // single crystal or crystal cluster
    TUMBLED, // tumble-polished stone
    CABOCHON, // polished dome-shaped stone
    SPHERE, // polished sphere
    POINT, // polished point or tower
    FACETED, // faceted gemstone
    CARVED, // carving or sculpture
    SLAB, // cut and/or polished slice
    BEAD, // bead or bead strand
    JEWELRY, // set in a piece of jewelry
    OTHER // anything else
}
