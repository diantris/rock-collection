// MaterialCategory.java - Broad category of a reference material
package com.rockcollection.material;

/**
 * Broad category of a reference material
 */
public enum MaterialCategory {
    MINERAL, // a mineral species or variety
    ROCK, // a rock (aggregate of minerals)
    ORGANIC, // of biological origin, e.g. amber, pearl
    MAN_MADE // glass, resin and other artificial materials
}
