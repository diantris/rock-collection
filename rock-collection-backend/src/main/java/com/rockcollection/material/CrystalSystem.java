package com.rockcollection.material;

/**
 * Crystal system of a mineral
 */
public enum CrystalSystem {
    CUBIC, // isometric
    TETRAGONAL,
    ORTHORHOMBIC,
    HEXAGONAL,
    TRIGONAL,
    MONOCLINIC,
    TRICLINIC,
    AMORPHOUS // no crystal structure, e.g. opal, obsidian
}
